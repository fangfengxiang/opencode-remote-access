const { readFileSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");

const argumentsList = process.argv.slice(2);
if (argumentsList.length > 1 || (argumentsList.length === 1 && argumentsList[0] !== "--check")) {
  console.error("Usage: node scripts/build.cjs [--check]");
  process.exit(2);
}

const root = join(__dirname, "..");
const read = (name) => readFileSync(join(root, "src", name), "utf8").trimEnd();
const moduleNames = ["gateway.cjs", "main.cjs", "control.cjs"];
const modules = moduleNames.map((name) => {
  return `  factories[${JSON.stringify(`./${name}`)}] = function (require, module, exports) {\n${read(name)}\n  };`;
});

const bundle = [
  "// Generated by scripts/build.cjs. Source files are under src/.",
  "(function (hostRequire, pluginModule, pluginExports) {",
  "  const factories = Object.create(null);",
  ...modules,
  "  const cache = new Map();",
  "",
  "  function load(id) {",
  "    if (!Object.hasOwn(factories, id)) {",
  '      if (id.startsWith("./") || id.startsWith("../")) {',
  '        throw new Error("Module is not included in the desktop bundle: " + id);',
  "      }",
  "      return hostRequire(id);",
  "    }",
  "    if (cache.has(id)) return cache.get(id).exports;",
  "    const entry = { exports: {} };",
  "    cache.set(id, entry);",
  "    try {",
  "      factories[id](load, entry, entry.exports);",
  "    } catch (error) {",
  "      cache.delete(id);",
  "      throw error;",
  "    }",
  "    return entry.exports;",
  "  }",
  "",
  "  (function (require, module, exports) {",
  read("desktop.cjs"),
  "  })(load, pluginModule, pluginExports);",
  "})(require, module, exports);",
  "",
].join("\n");

const output = join(root, "gui-experimental.cjs");
if (argumentsList[0] === "--check") {
  const manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  // npm can run these hooks while installing a Git dependency. The GUI bundle ships prebuilt.
  const preparationHooks = ["build", "prepare", "prepack", "preinstall", "install", "postinstall"];
  if (manifest.workspaces || preparationHooks.some((hook) => Object.hasOwn(manifest.scripts ?? {}, hook))) {
    console.error("The Git package must load the checked-in bundle without a preparation step.");
    process.exitCode = 1;
  }
  let current;
  try {
    current = readFileSync(output, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (bundle !== current) {
    console.error("Desktop bundle is missing or out of date. Run node scripts/build.cjs.");
    process.exitCode = 1;
  }
} else {
  writeFileSync(output, bundle);
}
